# 사람 세그멘테이션 + 배경 이미지 합성
# PyTorch torchvision의 사전학습 DeepLabV3 모델 사용

import cv2
import torch
import numpy as np
from PIL import Image
from torchvision.models.segmentation import (
    deeplabv3_resnet50,
    DeepLabV3_ResNet50_Weights
)


# ============================================================
# 1. 실행 장치 설정
# GPU(CUDA)가 있으면 GPU 사용, 없으면 CPU 사용
# ============================================================
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

print("사용 장치:", device)


# ============================================================
# 2. 사전학습된 DeepLabV3 세그멘테이션 모델 불러오기
# DEFAULT는 torchvision에서 제공하는 사전학습 가중치
# ============================================================
weights = DeepLabV3_ResNet50_Weights.DEFAULT

model = deeplabv3_resnet50(weights=weights)

# 모델을 CPU 또는 GPU로 이동
model = model.to(device)

# 학습이 아니라 추론만 하므로 평가 모드로 변경
model.eval()


# ============================================================
# 3. 모델에서 사용할 이미지 전처리 함수 가져오기
#
# resize, tensor 변환, normalize 등을
# 사전학습 모델의 규격에 맞게 자동 처리
# ============================================================
preprocess = weights.transforms()


# ============================================================
# 4. 모델이 구분할 수 있는 클래스 목록 확인
# 그중 "person" 클래스 번호 찾기
# ============================================================
categories = weights.meta["categories"]

person_class = categories.index("person")

print("person 클래스 번호:", person_class)


# ============================================================
# 5. 배경으로 사용할 이미지 불러오기
#
# back.jpg를 현재 .py 파일을 실행하는 폴더에 둔다.
# ============================================================
background = cv2.imread("back.jpg")

if background is None:
    raise FileNotFoundError(
        "back.jpg를 찾을 수 없습니다. "
        "back.jpg를 프로그램 실행 폴더에 넣어주세요."
    )


# ============================================================
# 6. 웹캠 열기
#
# 0 : 기본 웹캠
# 외장 카메라가 따로 있다면 1, 2 등이 될 수도 있음
# ============================================================
cap = cv2.VideoCapture(0)

if not cap.isOpened():
    raise RuntimeError("웹캠을 열 수 없습니다.")


# ============================================================
# 7. 웹캠 영상을 계속 읽으면서 처리
# ============================================================
while True:

    # --------------------------------------------------------
    # 웹캠에서 한 프레임 읽기
    # ret   : 정상적으로 읽었는지 여부
    # frame : 실제 영상 이미지
    # --------------------------------------------------------
    ret, frame = cap.read()

    if not ret:
        print("카메라 영상을 읽을 수 없습니다.")
        break


    # --------------------------------------------------------
    # 현재 웹캠 프레임 크기 구하기
    # --------------------------------------------------------
    height, width = frame.shape[:2]


    # --------------------------------------------------------
    # back.jpg를 현재 웹캠 화면 크기에 맞춤
    # --------------------------------------------------------
    back_resized = cv2.resize(
        background,
        (width, height)
    )


    # --------------------------------------------------------
    # OpenCV는 BGR 색상 순서 사용
    # PyTorch/PIL에서는 RGB를 사용하므로 변환
    # --------------------------------------------------------
    rgb_frame = cv2.cvtColor(
        frame,
        cv2.COLOR_BGR2RGB
    )


    # --------------------------------------------------------
    # numpy 배열을 PIL 이미지로 변환
    # --------------------------------------------------------
    pil_image = Image.fromarray(rgb_frame)


    # --------------------------------------------------------
    # DeepLabV3 입력 규격에 맞게 전처리
    #
    # [C, H, W]
    # →
    # unsqueeze(0)
    # →
    # [1, C, H, W]
    #
    # 1은 한 장의 이미지를 의미
    # --------------------------------------------------------
    input_tensor = preprocess(
        pil_image
    ).unsqueeze(0)

    input_tensor = input_tensor.to(device)


    # ========================================================
    # 8. 모델 추론
    # ========================================================
    with torch.no_grad():

        # output shape:
        # [batch, class, height, width]
        output = model(input_tensor)["out"]


    # ========================================================
    # 9. 각 픽셀에서 가장 확률이 높은 클래스 선택
    #
    # argmax(1):
    # 여러 클래스 중 가장 높은 값을 가진 클래스 번호 선택
    # ========================================================
    prediction = output.argmax(1)[0]


    # --------------------------------------------------------
    # Tensor → CPU → NumPy 배열
    # --------------------------------------------------------
    prediction = prediction.cpu().numpy()


    # ========================================================
    # 10. 사람(person) 영역만 True로 만드는 마스크 생성
    #
    # 사람 픽셀      → 1
    # 나머지 픽셀    → 0
    # ========================================================
    person_mask = (
        prediction == person_class
    ).astype(np.uint8)


    # --------------------------------------------------------
    # 모델 출력 마스크 크기와
    # 실제 웹캠 화면 크기가 다를 수 있으므로 resize
    #
    # segmentation mask이므로 INTER_NEAREST 사용
    # --------------------------------------------------------
    person_mask = cv2.resize(
        person_mask,
        (width, height),
        interpolation=cv2.INTER_NEAREST
    )


    # ========================================================
    # 11. 마스크를 3채널 이미지 형태로 변경
    #
    # 기존:
    # [H, W]
    #
    # 변경:
    # [H, W, 1]
    #
    # frame의 BGR 3채널과 계산하기 위해 필요
    # ========================================================
    mask_3channel = person_mask[:, :, np.newaxis]


    # ========================================================
    # 12. 사람과 새로운 배경 합성
    #
    # mask가 1인 부분:
    #     원래 웹캠 frame 사용
    #
    # mask가 0인 부분:
    #     back.jpg 사용
    # ========================================================
    result = (
        frame * mask_3channel
        +
        back_resized * (1 - mask_3channel)
    )


    # --------------------------------------------------------
    # 결과를 uint8 이미지 자료형으로 변환
    # --------------------------------------------------------
    result = result.astype(np.uint8)


    # ========================================================
    # 13. 결과 화면 출력
    # ========================================================
    cv2.imshow(
        "Person Segmentation",
        result
    )


    # ========================================================
    # 14. q 키를 누르면 프로그램 종료
    # ========================================================
    if cv2.waitKey(1) & 0xFF == ord("q"):
        break


# ============================================================
# 15. 프로그램 종료 시 웹캠과 OpenCV 창 정리
# ============================================================
cap.release()

cv2.destroyAllWindows()